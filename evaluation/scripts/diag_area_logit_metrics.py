"""CLI: compute area-vs-logit diagnostic metrics for a set of trained runs.

Pipeline:

    1. For each ``(short_name, run_dir)`` in the mapping YAML:
       a. If ``<logits_dir>/<short_name>/logits.pt`` is missing or ``--force``,
          run inference over the composed manifest (reuses
          :func:`evaluation.diagnostic.infer.export_logits_for_run`).
       b. Otherwise reuse the existing logits artifact as-is.
    2. Load each ``logits.pt`` and compute per-k and aggregated metrics via
       :func:`evaluation.diagnostic.area_logit_metrics.compute_metrics_for_model`.
    3. Write one tidy CSV at
       ``evaluation/data/processed/diagnostic_area_logit_metrics.csv``.

Defaults follow the project layout:
    --manifest  evaluation/data/raw/diagnostic/composed/manifest.jsonl
    --logits-dir evaluation/data/raw/diagnostic/logits
    --out-csv   evaluation/data/processed/diagnostic_area_logit_metrics.csv
    --mapping   evaluation/diagnostic/area_logit_models.yaml
"""
from __future__ import annotations

import argparse
import csv
import logging
import math
import os
from pathlib import Path
from typing import Dict, List, Mapping

import torch

from evaluation.common import (
    DIAGNOSTIC_DIR,
    PROCESSED_DIR,
    ensure_dirs,
    setup_logging,
)
from evaluation.diagnostic.area_logit_metrics import (
    CSV_COLUMNS,
    K_ALLOWED,
    MIN_AREA_DIFF,
    ModelMetricsRow,
    compute_metrics_for_model,
    row_to_dict,
)
from evaluation.diagnostic.infer import (
    InferConfig,
    _load_manifest,
    _manifest_sha256,
    _slug,
    export_logits_for_run,
)
from evaluation.offline_eval.io import load_mapping

_logger = logging.getLogger("evaluation.scripts.diag_area_logit_metrics")


_DEFAULT_MAPPING = (
    Path(__file__).resolve().parent.parent / "diagnostic" / "area_logit_models.yaml"
)
_DEFAULT_MANIFEST = DIAGNOSTIC_DIR / "composed" / "manifest.jsonl"
_DEFAULT_LOGITS_DIR = DIAGNOSTIC_DIR / "logits"
_DEFAULT_OUT_CSV = PROCESSED_DIR / "diagnostic_area_logit_metrics.csv"


# ---------------------------------------------------------------------------
# Logits caching
# ---------------------------------------------------------------------------


def _logits_path(logits_dir: Path, short_name: str) -> Path:
    return logits_dir / _slug(short_name) / "logits.pt"


def _ensure_logits(
    short_name: str,
    run_dir: str,
    *,
    manifest_path: Path,
    logits_dir: Path,
    infer_cfg_kwargs: Mapping[str, object],
    force: bool,
) -> Path:
    """Return the path of ``logits.pt`` for ``short_name``, generating it if needed."""
    out = _logits_path(logits_dir, short_name)
    if out.is_file() and not force:
        _logger.info("[%s] reusing existing logits at %s", short_name, out)
        return out

    _logger.info("[%s] running inference -> %s", short_name, out)
    cfg = InferConfig(
        manifest_path=str(manifest_path),
        out_dir=str(logits_dir),
        **dict(infer_cfg_kwargs),
    )
    rows, _meta = _load_manifest(cfg.manifest_path)
    manifest_sha = _manifest_sha256(cfg.manifest_path)
    manifest_dir = os.path.dirname(os.path.abspath(cfg.manifest_path))
    written = export_logits_for_run(
        short_name, run_dir, rows, cfg,
        manifest_dir=manifest_dir, manifest_sha=manifest_sha,
    )
    return Path(written)


# ---------------------------------------------------------------------------
# CSV writing
# ---------------------------------------------------------------------------


_HEADER_TEMPLATE = """\
# Area-vs-logit diagnostic metrics over the LabelMix composed dataset.
# Generated by ``evaluation/scripts/diag_area_logit_metrics.py``.
#
# One row per (model, k). ``k == "all"`` aggregates over k in {k_list}.
# Samples outside that k set are excluded from every row, including "all".
#
# Columns:
#   model          short model name from area_logit_models.yaml
#   k              composed-sample class count (3..6) or "all"
#   n_samples      composed samples contributing to this row (post k-filter)
#   spearman_mean  Metric 1 -- mean Spearman(area_ratios, logits) over present
#                  classes; samples with ties in either vector are skipped
#   spearman_n     number of samples with a defined Spearman value
#   pair_acc       Metric 2 -- fraction of eligible present-class pairs where
#                  argmax(area) implies argmax(logit); threshold
#                  |area_i - area_j| >= {min_area_diff}
#   pair_n         number of eligible pairs across all samples in the row
#   top_acc        Metric 3 -- fraction of samples where argmax(area) over
#                  present classes == argmax(logit) over present classes;
#                  samples with a tied largest area are skipped
#   top_n          number of samples with a non-tied largest area
#
# Models (short_name -> run_dir):
{model_lines}#
"""


def _build_header(
    models: Mapping[str, str],
    *,
    k_allowed: Sequence[int],
    min_area_diff: float,
) -> str:
    k_list = "{" + ", ".join(str(int(k)) for k in k_allowed) + "}"
    model_lines = "".join(
        f"#   {name:>14s}  {run_dir}\n" for name, run_dir in models.items()
    )
    return _HEADER_TEMPLATE.format(
        k_list=k_list,
        min_area_diff=min_area_diff,
        model_lines=model_lines,
    )


def _format_number(x: object) -> object:
    if isinstance(x, float):
        if math.isnan(x):
            return ""
        # 6 decimal places is plenty for three-digit-ish rates and still round-trips.
        return f"{x:.6f}"
    return x


def _write_csv(
    rows: List[ModelMetricsRow],
    out_csv: Path,
    *,
    header_text: str,
) -> None:
    out_csv.parent.mkdir(parents=True, exist_ok=True)
    with out_csv.open("w", newline="") as f:
        f.write(header_text)
        writer = csv.DictWriter(f, fieldnames=list(CSV_COLUMNS))
        writer.writeheader()
        for r in rows:
            d = row_to_dict(r)
            writer.writerow({k: _format_number(d[k]) for k in CSV_COLUMNS})
    _logger.info("Wrote %d rows to %s", len(rows), out_csv)


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------


def run(
    mapping_path: Path,
    manifest_path: Path,
    logits_dir: Path,
    out_csv: Path,
    *,
    force: bool,
    infer_cfg_kwargs: Mapping[str, object],
    k_allowed,
    min_area_diff: float,
) -> None:
    ensure_dirs()
    mapping: Dict[str, str] = dict(load_mapping(str(mapping_path)))
    _logger.info("Mapping has %d models: %s", len(mapping), list(mapping.keys()))

    all_rows: List[ModelMetricsRow] = []
    for short_name, run_dir in mapping.items():
        logits_path = _ensure_logits(
            short_name, run_dir,
            manifest_path=manifest_path, logits_dir=logits_dir,
            infer_cfg_kwargs=infer_cfg_kwargs, force=force,
        )
        blob = torch.load(str(logits_path), map_location="cpu", weights_only=False)
        rows = compute_metrics_for_model(
            blob,
            model_name=short_name,
            k_allowed=k_allowed,
            min_area_diff=min_area_diff,
        )
        all_rows.extend(rows)
        # Quick log summary for the aggregated row.
        agg = next((r for r in rows if r.k == "all"), None)
        if agg is not None:
            _logger.info(
                "[%s] all k: n=%d | spearman=%.4f (n=%d) | pair=%.4f (n=%d) | "
                "top=%.4f (n=%d)",
                short_name,
                agg.n_samples,
                agg.spearman_mean,
                agg.spearman_n,
                agg.pair_acc,
                agg.pair_n,
                agg.top_acc,
                agg.top_n,
            )

    _write_csv(
        all_rows,
        out_csv,
        header_text=_build_header(
            mapping, k_allowed=k_allowed, min_area_diff=min_area_diff,
        ),
    )


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def _parse_args(argv=None) -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__ or "")
    p.add_argument("--mapping", type=Path, default=_DEFAULT_MAPPING,
                   help="YAML/JSON {short_name: run_dir}.")
    p.add_argument("--manifest", type=Path, default=_DEFAULT_MANIFEST,
                   help="Composed dataset manifest.jsonl.")
    p.add_argument("--logits-dir", type=Path, default=_DEFAULT_LOGITS_DIR,
                   help="Directory to cache <name>/logits.pt artifacts.")
    p.add_argument("--out-csv", type=Path, default=_DEFAULT_OUT_CSV,
                   help="Output CSV path.")
    p.add_argument("--force", action="store_true",
                   help="Re-run inference even when <name>/logits.pt exists.")
    # Inference knobs (mirroring evaluation/diagnostic/infer.py defaults).
    p.add_argument("--checkpoint-name", default="model_best.pth.tar")
    p.add_argument("--use-ema", action=argparse.BooleanOptionalAction, default=True)
    p.add_argument("--batch-size", type=int, default=64)
    p.add_argument("--device", default="cuda")
    p.add_argument("--amp", action=argparse.BooleanOptionalAction, default=True)
    p.add_argument("--amp-dtype", default="bfloat16", choices=["bfloat16", "float16"])
    # Metric knobs (currently diagnostic; defaults match the task spec).
    p.add_argument("--k-allowed", type=int, nargs="+", default=list(K_ALLOWED),
                   help="Restrict to these k values (default: 3 4 5 6).")
    p.add_argument("--min-area-diff", type=float, default=MIN_AREA_DIFF,
                   help="Metric 2 pair-inclusion threshold (default: 0.05).")
    p.add_argument("-v", "--verbose", action="store_true")
    return p.parse_args(argv)


def main(argv=None) -> int:
    args = _parse_args(argv)
    setup_logging(level="INFO" if args.verbose else "WARNING")

    infer_cfg_kwargs = dict(
        checkpoint_name=args.checkpoint_name,
        use_ema=args.use_ema,
        batch_size=int(args.batch_size),
        device=args.device,
        amp=args.amp,
        amp_dtype=args.amp_dtype,
    )
    run(
        mapping_path=args.mapping,
        manifest_path=args.manifest,
        logits_dir=args.logits_dir,
        out_csv=args.out_csv,
        force=bool(args.force),
        infer_cfg_kwargs=infer_cfg_kwargs,
        k_allowed=tuple(int(k) for k in args.k_allowed),
        min_area_diff=float(args.min_area_diff),
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
